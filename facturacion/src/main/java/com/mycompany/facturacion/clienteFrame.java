    private void UploadButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UploadButtonActionPerformed

        String documento = DocField.getText().trim();
        String nombre = NameField.getText().trim();
        String correo = Mailfield.getText().trim();
        String telefono = PhoneField.getText().trim();
        String direccion = DirectionField.getText().trim();

    // Validar los campos obligatorios.
    if (documento.isEmpty() || nombre.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "El documento y el nombre son obligatorios.",
            "Datos incompletos",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    try (java.sql.Connection cn = conexion.conectar()) {

        // Comprobar si el documento ya está registrado.
        String sqlVerificar =
            "SELECT id_cliente FROM cliente "
            + "WHERE numero_documento = ?";

        try (java.sql.PreparedStatement pstVerificar =
                cn.prepareStatement(sqlVerificar)) {

            pstVerificar.setString(1, documento);

            try (java.sql.ResultSet rs =
                    pstVerificar.executeQuery()) {

                if (rs.next()) {
                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Ya existe un cliente registrado con "
                        + "el documento " + documento + ".",
                        "Cliente duplicado",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                    );

                    DocField.requestFocusInWindow();
                    return;
                }
            }
        }

        // Registrar únicamente si el documento no existe.
        String sqlInsertar =
            "INSERT INTO cliente "
            + "(numero_documento, nombre, correo, telefono, direccion) "
            + "VALUES (?, ?, ?, ?, ?)";

        try (java.sql.PreparedStatement pst =
                cn.prepareStatement(sqlInsertar)) {

            pst.setString(1, documento);
            pst.setString(2, nombre);
            pst.setString(3, correo.isEmpty() ? null : correo);
            pst.setString(4, telefono.isEmpty() ? null : telefono);
            pst.setString(5, direccion.isEmpty() ? null : direccion);

            pst.executeUpdate();
        }

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "¡Cliente registrado con éxito!",
            "Registro completado",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        cargarTablaClientes();
        limpiarCampos();

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No se pudo registrar el cliente:\n" + e.getMessage(),
            "Error de base de datos",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_UploadButtonActionPerformed

    private void UpdateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateButtonActionPerformed
        String idTexto = IDClientTextField.getText().trim();
        String documento = DocField.getText().trim();
        String nombre = NameField.getText().trim();
        String correo = Mailfield.getText().trim();
        String telefono = PhoneField.getText().trim();
        String direccion = DirectionField.getText().trim();

        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecciona primero un cliente de la tabla que deseas actualizar.",
                "Ningún cliente seleccionado",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (documento.isEmpty() || nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "El documento y el nombre son obligatorios. :U",
                "Datos incompletos",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!correoValido(correo)) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Introduce un correo electrónico válido.",
                "Correo no válido",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            Mailfield.requestFocusInWindow();
            return;
        }

        final int idCliente;
        try {
            idCliente = Integer.parseInt(idTexto);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "El ID del cliente seleccionado no es válido.",
                "ID incorrecto",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        String sql = "UPDATE cliente SET numero_documento = ?, nombre = ?, "
        + "correo = ?, telefono = ?, direccion = ? "
        + "WHERE id_cliente = ?";

        try (
            java.sql.Connection cn = conexion.conectar();
            java.sql.PreparedStatement pst = cn.prepareStatement(sql)
        ) {
            pst.setString(1, documento);
            pst.setString(2, nombre);
            pst.setString(3, correo.isEmpty() ? null : correo);
            pst.setString(4, telefono.isEmpty() ? null : telefono);
            pst.setString(5, direccion.isEmpty() ? null : direccion);
            pst.setInt(6, idCliente);

            int filasAfectadas = pst.executeUpdate();
            if (filasAfectadas > 0) {
                cargarTablaClientes();
                limpiarCampos();
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Cliente actualizado correctamente.",
                    "Actualización completada",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
                );
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se encontró el cliente que intentas actualizar.",
                    "Cliente no encontrado",
                    javax.swing.JOptionPane.WARNING_MESSAGE
                );
                cargarTablaClientes();
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se pudo actualizar el cliente:\n" + e.getMessage(),
                "Error de base de datos",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_UpdateButtonActionPerformed

    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        String idTexto = IDClientTextField.getText().trim();

        // 2. Validar que no esté vacío (significa que no ha seleccionado nada en la tabla)
        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Por favor, selecciona primero un cliente de la tabla para poder eliminarlo.",
                "Ningún cliente seleccionado",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // 3. Solicitar confirmación al usuario (Buena práctica de UX)
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Estás seguro de que deseas eliminar este cliente permanentemente?",
            "Confirmar eliminación",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE
        );

        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {

            String sql = "DELETE FROM cliente WHERE id_cliente = ?";

            try (
                java.sql.Connection cn = conexion.conectar();
                java.sql.PreparedStatement pst = cn.prepareStatement(sql)
            ) {
                int idCliente = Integer.parseInt(idTexto);
                pst.setInt(1, idCliente);

                int filasAfectadas = pst.executeUpdate();

                if (filasAfectadas > 0) {
                    cargarTablaClientes();
                    limpiarCampos();

                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "El cliente ha sido eliminado correctamente de la base de datos.",
                        "Eliminación completada",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                    );
                } else {
                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No se encontró el cliente en la base de datos. Es posible que ya haya sido eliminado.",
                        "Cliente no encontrado",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                    );
                    cargarTablaClientes();
                }

            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El ID del cliente no es un número válido.",
                    "Error de formato",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
            } catch (java.sql.SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ocurrió un error al intentar eliminar el cliente:\n" + e.getMessage(),
                    "Error de Base de Datos",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_DeleteButtonActionPerformed

    // CARGAR LOS CLIENTES DESDE LA BASE DE DATOS
private void cargarTablaClientes() {

    String sql = "SELECT id_cliente, numero_documento, nombre, "
               + "correo, telefono, direccion "
               + "FROM cliente ORDER BY id_cliente";

    javax.swing.table.DefaultTableModel modelo =
        new javax.swing.table.DefaultTableModel(
            new Object[][] {},
            new String[] {
                "ID Cliente",
                "Documento",
                "Nombre",
                "Correo",
                "Teléfono",
                "Dirección"
            }
        ) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

    try (
        java.sql.Connection cn = conexion.conectar();
        java.sql.PreparedStatement pst = cn.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery()
    ) {

        while (rs.next()) {
            modelo.addRow(new Object[] {
                rs.getInt("id_cliente"),
                rs.getString("numero_documento"),
                rs.getString("nombre"),
                rs.getString("correo"),
                rs.getString("telefono"),
                rs.getString("direccion")
            });
        }

        TableClientes.setModel(modelo);

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No se pudieron cargar los clientes:\n" + e.getMessage(),
            "Error de base de datos",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}



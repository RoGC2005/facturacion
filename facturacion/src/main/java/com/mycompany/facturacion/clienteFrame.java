// VALIDAR EL FORMATO DEL CORREO ELECTRÓNICO
private boolean correoValido(String correo) {

    if (correo == null || correo.trim().isEmpty()) {
        return true;
    }

    return correo.matches(
        "^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$"
    );

}

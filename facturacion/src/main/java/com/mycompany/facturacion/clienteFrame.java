// Añadir etiquetas y campos sin fijarles un ancho rígido.
private void agregarControlFormulario(
        java.awt.Component componente,
        int columna,
        int fila,
        boolean expandir) {

    java.awt.GridBagConstraints gbc =
        new java.awt.GridBagConstraints();

    gbc.gridx = columna;
    gbc.gridy = fila;

    gbc.weightx = expandir ? 1.0 : 0.0;
    gbc.weighty = 0.0;

    gbc.fill = expandir
        ? java.awt.GridBagConstraints.HORIZONTAL
        : java.awt.GridBagConstraints.NONE;

    gbc.anchor = java.awt.GridBagConstraints.WEST;

    gbc.insets = new java.awt.Insets(5, 6, 5, 6);

    ClientInfoPanel.add(componente, gbc);
}

// CARGAR LOS DATOS DEL CLIENTE SELECCIONADO
private void configurarSeleccionTabla() {

    TableClientes.getSelectionModel()
        .addListSelectionListener(evento -> {

            if (evento.getValueIsAdjusting()) {
                return;
            }

            int fila = TableClientes.getSelectedRow();

            if (fila == -1) {
                return;
            }

            // Obtener la fila correspondiente del modelo.
            int filaModelo =
                TableClientes.convertRowIndexToModel(fila);

            // Recuperar y mostrar el ID del cliente.
            Object id = TableClientes.getValueAt(filaModelo, 0);
            IDClientTextField.setText(
                id == null ? "" : id.toString()
            );

            // Recuperar los datos restantes.
            Object documento =
                TableClientes.getValueAt(filaModelo, 1);

            Object nombre =
                TableClientes.getValueAt(filaModelo, 2);

            Object correo =
                TableClientes.getValueAt(filaModelo, 3);

            Object telefono =
                TableClientes.getValueAt(filaModelo, 4);

            Object direccion =
                TableClientes.getValueAt(filaModelo, 5);

            DocField.setText(
                documento == null ? "" : documento.toString()
            );

            NameField.setText(
                nombre == null ? "" : nombre.toString()
            );

            Mailfield.setText(
                correo == null ? "" : correo.toString()
            );

            PhoneField.setText(
                telefono == null ? "" : telefono.toString()
            );

            DirectionField.setText(
                direccion == null ? "" : direccion.toString()
            );
        });
}
